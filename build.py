"""Compile or rebuild the plugin layer of a supported, user-supplied APK."""
import argparse
import copy
import hashlib
import json
import os
import platform
import re
import shutil
import struct
import subprocess
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PROFILES = {
    'arc701': ('classes3.dex', 'fa7ab65059ae2639a54b2daf37c0cd2d2084f620c2c322e8252f740e713fc6a1'),
    'shell': ('classes3.dex', 'a2633fe805b55627f0143ca7f7f08555cc80b6cff13b4e0ddfa294bbe64df6ed'),
    'full': ('classes4.dex', '143e1c8bd6683a93ac02f895f500b3ff2a1143a528f1dab56788fa655d3cbb23'),
}

def run(*args):
    subprocess.run([str(x) for x in args], check=True)

def hash_file(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--variant', choices=PROFILES, required=True)
    parser.add_argument('--sdk', type=Path, default=os.environ.get('ANDROID_HOME') or os.environ.get('ANDROID_SDK_ROOT'))
    parser.add_argument('--ndk', type=Path, default=os.environ.get('ANDROID_NDK_HOME'))
    parser.add_argument('--java-home', type=Path, default=os.environ.get('JAVA_HOME'))
    parser.add_argument('--android-jar', type=Path)
    parser.add_argument('--build-tools', type=Path)
    parser.add_argument('--base-apk', type=Path)
    parser.add_argument('--output', type=Path, default=ROOT/'out')
    parser.add_argument('--compile-only', action='store_true')
    parser.add_argument('--unsigned', action='store_true')
    parser.add_argument('--keystore', type=Path)
    parser.add_argument('--key-alias', default='enhanced')
    parser.add_argument('--password-env', default='ARCPRACTICE_SIGNING_PASS')
    args = parser.parse_args()
    android = args.android_jar or (args.sdk/'platforms/android-35/android.jar' if args.sdk else None)
    bt = args.build_tools or (args.sdk/'build-tools/35.0.0' if args.sdk else None)
    ndk = args.ndk or (args.sdk/'ndk/29.0.14206865' if args.sdk else None)
    if not android or not bt or not ndk or not args.java_home:
        parser.error('Provide Android SDK/platform, build-tools, NDK and JAVA_HOME; see BUILDING.md')
    host = {'Windows':'windows-x86_64', 'Linux':'linux-x86_64', 'Darwin':'darwin-x86_64'}[platform.system()]
    suffix = '.exe' if platform.system() == 'Windows' else ''
    clang = ndk/'toolchains/llvm/prebuilt'/host/'bin'/('clang++'+suffix)
    java, javac = [args.java_home/'bin'/(name+suffix) for name in ['java','javac']]
    align = bt/('zipalign'+suffix)
    for path in [android, clang, java, javac, bt/'lib/d8.jar', align, bt/'lib/apksigner.jar']:
        if not path.is_file():
            parser.error('A required SDK/JDK tool is missing; check the supplied directories')
    dex, expected = PROFILES[args.variant]
    if not args.compile_only:
        if not args.base_apk or not args.base_apk.is_file():
            parser.error('--base-apk must be a supported shell r3 or full r10 APK (or its r2/r9 predecessor)')
        with zipfile.ZipFile(args.base_apk) as archive:
            actual = hashlib.sha256(archive.read('lib/arm64-v8a/libcocos2dcpp.so')).hexdigest()
            if actual != expected or dex not in archive.namelist():
                parser.error('Unsupported APK native profile or plugin DEX layout; refusing to patch')
        if not args.unsigned and (not args.keystore or not args.keystore.is_file() or not os.environ.get(args.password_env)):
            parser.error('Signing requires --keystore and the environment variable named by --password-env')
    project = ROOT/'variants'/args.variant
    build = args.output.resolve()/args.variant
    classes, dexdir = build/'classes', build/'dex'
    # Remove stale generated bytecode only inside this exact output directory.
    if classes.exists():
        assert classes.resolve().parent == build
        shutil.rmtree(classes)
    classes.mkdir(parents=True)
    dexdir.mkdir(exist_ok=True)
    run(clang, '--target=aarch64-linux-android24', '-shared', '-fPIC', '-O2', '-std=c++17', '-static-libstdc++',
        '-Wl,-z,max-page-size=16384', '-DANDROID', '-DSOUNDTOUCH_DISABLE_X86_OPTIMIZATIONS',
        '-I'+str(ROOT/'third_party/signalsmith-stretch'), '-I'+str(ROOT/'third_party/signalsmith-linear/include'),
        '-I'+str(ROOT/'third_party/soundtouch/include'), '-I'+str(ROOT/'third_party/soundtouch/source/SoundTouch'),
        project/'native/practice.cpp', *sorted((ROOT/'third_party/soundtouch/source/SoundTouch').glob('*.cpp')),
        '-llog', '-ldl', '-o', build/'libarcpractice.so')
    run(javac, '-encoding', 'UTF-8', '-source', '8', '-target', '8', '-classpath', android, '-d', classes,
        *sorted((project/'java/moe/practice').glob('*.java')))
    run(java, '-cp', bt/'lib/d8.jar', 'com.android.tools.r8.D8', '--min-api', '24', '--lib', android,
        '--output', dexdir, *sorted(classes.rglob('*.class')))
    if args.compile_only:
        print('Plugin native library and DEX compiled successfully: '+args.variant)
        return
    replacements = {dex:dexdir/'classes.dex', 'lib/arm64-v8a/libarcpractice.so':build/'libarcpractice.so'}
    unsigned = build/'unsigned.apk'
    # Preserve compressed game payloads, including very large assets, byte for byte.
    zipfile.ZIP64_LIMIT = 0xffffffff
    with zipfile.ZipFile(args.base_apk) as source, args.base_apk.open('rb') as raw, zipfile.ZipFile(unsigned,'w') as target:
        for entry in source.infolist():
            if entry.filename in replacements or entry.filename.upper() == 'META-INF/MANIFEST.MF' or re.fullmatch(r'META-INF/[^/]+\.(SF|RSA|DSA|EC)',entry.filename,re.I):
                continue
            if entry.flag_bits & 8:
                raise ValueError('Unsupported ZIP data descriptor')
            raw.seek(entry.header_offset)
            header = raw.read(30)
            if header[:4] != b'PK\x03\x04':
                raise ValueError('Invalid ZIP entry')
            name, extra = struct.unpack_from('<HH',header,26)
            length = 30+name+extra+entry.compress_size
            item = copy.copy(entry)
            item.header_offset = target.fp.tell()
            target._writecheck(item)
            target._didModify = True
            raw.seek(entry.header_offset)
            while length:
                chunk = raw.read(min(length,8*1024*1024))
                if not chunk:
                    raise ValueError('Unexpected end of APK')
                target.fp.write(chunk)
                length -= len(chunk)
            target.filelist.append(item)
            target.NameToInfo[item.filename] = item
            target.start_dir = target.fp.tell()
        for name,path in replacements.items():
            target.write(path,name,compress_type=zipfile.ZIP_STORED)
    aligned = build/'aligned.apk'
    run(align,'-P','16','-f','4',unsigned,aligned)
    output = build/('Arcaea-Practice-'+args.variant+'.apk')
    if args.unsigned:
        shutil.copyfile(aligned,output)
    else:
        run(java,'-jar',bt/'lib/apksigner.jar','sign','--ks',args.keystore,'--ks-key-alias',args.key_alias,
            '--ks-pass','env:'+args.password_env,'--key-pass','env:'+args.password_env,'--out',output,aligned)
        run(java,'-jar',bt/'lib/apksigner.jar','verify','--verbose',output)
    run(align,'-c','-P','16','4',output)
    with zipfile.ZipFile(args.base_apk) as before,zipfile.ZipFile(output) as after:
        assert len(after.namelist()) == len(set(after.namelist()))
        preserved = 0
        for item in before.infolist():
            if item.filename in replacements or item.filename.startswith('META-INF/'):
                continue
            other = after.getinfo(item.filename)
            assert (item.CRC,item.file_size,item.compress_size) == (other.CRC,other.file_size,other.compress_size),item.filename
            preserved += 1
        for name,path in replacements.items():
            assert after.read(name) == path.read_bytes()
        assert after.testzip() is None
    report = dict(apk=output.name,variant=args.variant,sha256=hash_file(output),bytes=output.stat().st_size,
                  preserved_entries=preserved,game_native_sha256=expected,zip_crc='all entries passed',
                  signature='unsigned' if args.unsigned else 'v2/v3 verified',alignment='16KB verified')
    (build/'verification.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print('Build and verification completed: '+output.name)

if __name__ == '__main__':
    main()
